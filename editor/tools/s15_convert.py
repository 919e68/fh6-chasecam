"""Converts the S15 preview car model to an embedded mesh (src/gen/s15_mesh.inc).

    pip install numpy fast-simplification
    python3 editor/tools/s15_convert.py path/to/R0JJ9OLK2RFGAJSBV0XC3JIAA.obj

Source: "Nissan Silvia Drift Tuned (S15)" by VuckyZ
https://sketchfab.com/3d-models/nissan-silvia-drift-tuned-s15-84b63a057e36488589392a19b9313e2b
Licensed under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
Changes: interior, suspension, brakes removed; simplified to about 4,000
triangles; rescaled to 4,445 mm long; textures and materials dropped.
"""
import os, sys, collections
import numpy as np
import fast_simplification

LENGTH = 4.445                        # metres, nose to tail
# material -> (part, target triangles). part: 0 body, 1 wheel, 2 detail. Not listed = dropped.
KEEP = {
    'CAR_BODY_PAINT': (0, 1700), 'MATT': (0, 700), 'BODY_NUMBER_PAINT': (0, 60), 'WINDOW_GLASS': (0, 260),
    'LIGHTS_GLASS': (2, 160), 'LIGHTS_POD': (2, 110), 'LIGHTS_SATIN': (2, 40), 'GRILLS': (2, 60), 'SHINY_METAL': (2, 80),
    'TARMAC_TYRE_WALL': (1, 320), 'TARMAC_TYRE_TREAD': (1, 160), 'TARMAC_WHEEL': (1, 420),
}

def load(path):
    V = []; parts = collections.defaultdict(list); mtl = '?'
    for line in open(path, errors='replace'):
        if line.startswith('v '): V.append(tuple(map(float, line.split()[1:4])))
        elif line.startswith('usemtl'): mtl = line.split(None, 1)[1].strip()
        elif line.startswith('f '):
            idx = [int(t.split('/')[0]) for t in line.split()[1:]]
            idx = [i - 1 if i > 0 else len(V) + i for i in idx]
            for k in range(1, len(idx) - 1): parts[mtl].append((idx[0], idx[k], idx[k + 1]))
    return np.array(V, dtype=np.float64), parts

def weld(P, T):
    """Merge vertices at the same position (UV seams) so simplification can collapse across them."""
    key = np.round(P / 1e-5).astype(np.int64)
    _, first, inv = np.unique(key, axis=0, return_index=True, return_inverse=True)
    T = inv.reshape(-1)[T]
    T = T[(T[:, 0] != T[:, 1]) & (T[:, 1] != T[:, 2]) & (T[:, 0] != T[:, 2])]
    return P[first], T

def drop_slivers(P, T, longest=0.35, thin=0.08):
    """Remove long, nearly flat triangles left by simplification. In a see-through
    wireframe they read as streaks across the body; their area is negligible."""
    a, b, c = P[T[:, 0]], P[T[:, 1]], P[T[:, 2]]
    e = np.stack([np.linalg.norm(b - a, axis=1), np.linalg.norm(c - b, axis=1), np.linalg.norm(a - c, axis=1)], axis=1).max(axis=1)
    area2 = np.linalg.norm(np.cross(b - a, c - a), axis=1)
    keep = ~((e > longest) & (area2 / np.maximum(e * e, 1e-12) < thin))
    return T[keep]

def main(path, out):
    V, parts = load(path)
    # model space: Y up, front toward +X, centred. Car space: x right, y up from the ground, z forward.
    s = LENGTH / (V[:, 0].max() - V[:, 0].min())
    ground = V[:, 1].min()
    C = np.stack([V[:, 2] * s, (V[:, 1] - ground) * s, V[:, 0] * s], axis=1)
    allP, allT, allPart = [], [], []
    base = 0
    for mtl, (part, target) in KEEP.items():
        if mtl not in parts: continue
        T = np.array(parts[mtl], dtype=np.int64)
        used, T = np.unique(T, return_inverse=True)
        P, T = weld(C[used], T.reshape(-1, 3))
        if len(T) > target:
            P2, T2 = fast_simplification.simplify(P, T.astype(np.int32), target_count=target)
            P, T = np.asarray(P2, dtype=np.float64), np.asarray(T2, dtype=np.int64)
            T = drop_slivers(P, T)
        allP.append(P); allT.append(T + base); allPart += [part] * len(T); base += len(P)
        print('%-18s %5d -> %5d triangles' % (mtl, len(parts[mtl]), len(T)))
    P = np.concatenate(allP); T = np.concatenate(allT)
    # wind every triangle so its normal points away from the body centre
    centre = np.array([0, P[:, 1].mean(), 0])
    n = np.cross(P[T[:, 1]] - P[T[:, 0]], P[T[:, 2]] - P[T[:, 0]])
    away = ((P[T].mean(axis=1) - centre) * n).sum(axis=1)
    if (away < 0).sum() > (away > 0).sum(): T = T[:, [0, 2, 1]]
    mm = np.round(P * 1000).astype(np.int32)
    assert len(P) < 65536 and np.abs(mm).max() < 32768
    with open(out, 'w', newline='\n') as f:
        f.write('// Generated by tools/s15_convert.py. Do not edit.\n')
        f.write('// "Nissan Silvia Drift Tuned (S15)" by VuckyZ, CC BY 4.0\n')
        f.write('// https://sketchfab.com/3d-models/nissan-silvia-drift-tuned-s15-84b63a057e36488589392a19b9313e2b\n')
        f.write('// Changed: interior and running gear removed, simplified, rescaled, materials dropped.\n')
        f.write('static const int S15_NV = %d, S15_NT = %d;\n' % (len(P), len(T)))
        def arr(name, ctype, vals, per=12):
            f.write('static const %s %s[] = {\n' % (ctype, name))
            for i in range(0, len(vals), per): f.write('  ' + ', '.join(str(int(v)) for v in vals[i:i + per]) + ',\n')
            f.write('};\n')
        arr('S15_V', 'short', mm.reshape(-1))            # millimetres, x y z
        arr('S15_T', 'unsigned short', T.reshape(-1))
        arr('S15_P', 'unsigned char', allPart, 32)
    print('total %d vertices, %d triangles -> %s' % (len(P), len(T), out))
    print('size: length %.3f, width %.3f, height %.3f m' % tuple(np.ptp(P[:, k]) for k in (2, 0, 1)))

if __name__ == '__main__':
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, 'src', 'gen', 's15_mesh.inc'))
